  function escapeHtml(str) {
    if (str === null || str === undefined) return '';
    return String(str)
      .replace(/&/g, '&amp;')
      .replace(/</g, '&lt;')
      .replace(/>/g, '&gt;')
      .replace(/"/g, '&quot;')
      .replace(/'/g, '&#39;');
  }

  function classNames(...args) {
    return args
      .flat()
      .filter(Boolean)
      .map(s => String(s).trim())
      .join(' ');
  }

